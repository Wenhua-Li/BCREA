# ---------------------------------------------------------------- 读 CSV
def load(name: str) -> list[dict]:
    path = ANA / (name + ".csv")
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def g(row: dict, key: str) -> float:
    v = row.get(key)
    if v is None or v == "" or str(v).lower() == "nan":
        return NAN
    return float(v)


def med(xs) -> float:
    a = [x for x in xs if x is not None and math.isfinite(x)]
    return statistics.median(a) if a else NAN


def mean(xs) -> float:
    a = [x for x in xs if x is not None and math.isfinite(x)]
    return sum(a) / len(a) if a else NAN


# ---------------------------------------------------------------- 排版工具
def T(s: str):
    """tex / md 同一串。"""
    return (s, s)


def inst_cell(inst: str):
    """实例名：tex 里下划线要转义，md 里保持原名。"""
    return (inst.replace("_", "\\_"), inst)


def inst_label_cell(inst: str):
    """论文渲染层用的中性实例标签：gen{scale}_{conc|disp}_{nn} → C/D 编号，
    基准实例 i* 保持原名（与参考文献的基准套件标识一致）。md 人读版保持原名。"""
    if inst.startswith("gen"):
        parts = inst.split("_")  # gen24/conc/01
        kind = {"conc": "C", "disp": "D"}[parts[1]]
        label = f"{kind}{int(parts[2])}"
        return (label, inst)
    return (inst.replace("_", "\\_"), inst)


def num(x: float, nd: int = 2) -> str:
    if not math.isfinite(x):
        return "--"
    s = f"{x:.{nd}f}"
    if s.startswith("-") and float(s) == 0:
        s = s[1:]
    return s


def texnum(x: float, nd: int = 2) -> str:
    """LaTeX 单元格：带符号的数用数学模式（负号才好看）。"""
    s = num(x, nd)
    if s == "--":
        return s
    return "$" + s + "$" if s[0] in "+-" else s


def pair_num(x: float, nd: int = 2):
    return (texnum(x, nd), num(x, nd))


def pair_signed(x: float, nd: int = 2):
    """带符号的差，正负号必须显式（tex 用数学模式）。"""
    if not math.isfinite(x):
        return ("--", "--")
    if abs(x) < 0.5 * 10 ** (-nd):
        x = 0.0
    return (f"${x:+.{nd}f}$", f"{x:+.{nd}f}")


def pair_pct(x: float, nd: int = 1):
    s = num(x, nd)
    if s == "--":
        return ("--", "--")
    return (s + r"\%", s + "%")


def pval(p: float):
    """p 值：md 用科学计数 e 记法，tex 用 a×10^b。"""
    if not math.isfinite(p):
        return ("--", "--")
    if p >= 1e-3:
        return (f"${p:.3f}$", f"{p:.3f}")
    e = int(math.floor(math.log10(p)))
    m = p / (10.0 ** e)
    if m >= 9.95:
        m /= 10.0
        e += 1
    return (f"${m:.1f}\\times10^{{{e}}}$", f"{m:.1f}e{e}")


