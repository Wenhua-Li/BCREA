@dataclass
class Tab:
    fname: str
    caption: str
    label: str
    blocks: list
    note: str = ""
    star: bool = False
    md_title: str = ""
    md_note: str = ""
    label_alias: str = ""
    font: str = "\\footnotesize"
    colsep: str = "3pt"


def render_tex(t: Tab) -> str:
    env = "table*" if t.star else "table"
    out = [HEADER_NOTE, f"\\begin{{{env}}}[!t]"]
    out.append(f"\\caption{{{t.caption}}}")
    out.append(f"\\label{{{t.label}}}")
    if t.label_alias:
        out.append(f"\\label{{{t.label_alias}}}% alias for existing \\ref")
    out.append("\\centering" + t.font)
    out.append(f"\\setlength{{\\tabcolsep}}{{{t.colsep}}}")
    for bi, blk in enumerate(t.blocks):
        if bi:
            out.append("\\vspace{2pt}")
        out.append(f"\\begin{{tabular}}{{{blk.align}}}")
        out.append("\\toprule")
        for h in blk.head:
            if isinstance(h, str):
                out.append(h)
            else:
                out.append(" & ".join(c[0] for c in h) + " \\\\")
        out.append("\\midrule")
        for r in blk.rows:
            if r is None:
                out.append("\\midrule")
            else:
                out.append(" & ".join(c[0] for c in r) + " \\\\")
        out.append("\\bottomrule")
        out.append("\\end{tabular}")
    if t.note:
        out.append("\\par\\vspace{1pt}\\raggedright\\scriptsize " + t.note)
    out.append(f"\\end{{{env}}}")
    return "\n".join(out) + "\n"


def render_md(t: Tab) -> str:
    out = [f"## {t.md_title}", ""]
    for blk in t.blocks:
        out.append("| " + " | ".join(blk.md_head) + " |")
        out.append("|" + "|".join(["---"] * len(blk.md_head)) + "|")
        for r in blk.rows:
            if r is None:
                continue
            out.append("| " + " | ".join(c[1] for c in r) + " |")
        out.append("")
    if t.md_note:
        out.append(t.md_note)
        out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- 数据装载
class Data:
    def __init__(self) -> None:
        self.nom = {}
        self.deg = {}
        self.rc = {}
        self.scale = {}
        self.units = {n: [] for n in SCALES}
        self._load_units()

        self.summary = {(int(r["n_target"]), r["method"]): r
                        for r in load("v3_summary_method_scale")}
        self.phen = {int(r["n_target"]): r for r in load("v3_phenomenon_scale")}
        self.mstar = {(int(r["n_target"]), r["method"], int(r["gamma"])): r
                      for r in load("v3_mstar_dist")}
        self.stats = {(r["subset"], r["metric"], r["variant"], r["opponent"]): r
                      for r in load("v3_stats")}
        self.menu = {(int(r["n_target"]), r["method"], int(r["m"])): r
                     for r in load("v3_menu_switch_summary")}
        self.timing = {(r["segment"], r["n_target"]): r for r in load("v3_timing")}
        self.reopt = load("v3_reopt")
        self.menu_rows = None   # 需要时才读（35k 行）

        # 共同参考：同实例 nominal 池 10 种子的名义最优最大值
        self.ref = {}
        for (m, inst, s), r in self.nom.items():
            if m == "nominal":
                b = g(r, "best_nominal")
                self.ref[inst] = max(self.ref.get(inst, -math.inf), b)

    def _load_units(self) -> None:
        for name, store in (("v3_nominal", self.nom), ("v3_degradation", self.deg),
                            ("v3_rc", self.rc)):
            for r in load(name):
                n = int(r["n_target"])
                self.scale[r["instance"]] = n
                store[(r["method"], r["instance"], int(r["seed"]))] = r
        for (m, inst, s) in self.nom:
            if m == "nominal":
                self.units[self.scale[inst]].append((inst, s))
        for n in SCALES:
            self.units[n].sort()

    # ---- 聚合
    def units_of(self, n: int):
        return self.units[n]

    def per_method_scale(self, method: str, metric_store, key: str, n: int) -> list[float]:
        return [g(metric_store[(method, i, s)], key) for (i, s) in self.units[n]]

    def median_metric(self, method: str, n: int, metric: str) -> float:
        if metric == "rc5":
            return med(self.per_method_scale(method, self.rc, "rc5", n))
        if metric == "deg":
            return med(self.per_method_scale(method, self.deg, "deg_in_band_mean", n))
        if metric == "best":
            return med(self.per_method_scale(method, self.nom, "best_nominal", n))
        raise KeyError(metric)

    def nominal_cost(self, method: str, n: int) -> float:
        vals = []
        for (i, s) in self.units[n]:
            b = g(self.nom[(method, i, s)], "best_nominal")
            ref = self.ref[i]
            if math.isfinite(b) and ref > 0:
                vals.append((ref - b) / ref * 100.0)
        return med(vals)

    def load_menu_rows(self):
        if self.menu_rows is None:
            self.menu_rows = load("v3_menu_switch")
        return self.menu_rows


# ---------------------------------------------------------------- 自检
def check_against_summary(d: Data) -> None:
    bad = []
    for n in SCALES:
        for m in SIX:
            s = d.summary[(n, m)]
            for metric, key in (("best", "best_nominal_median"),
                                ("deg", "deg_in_band_median"),
                                ("rc5", "rc5_median")):
                calc = d.median_metric(m, n, metric)
                ref = g(s, key)
                if abs(calc - ref) > 1e-9:
                    bad.append(f"{n}/{m}/{metric}: 重算 {calc!r} != summary {ref!r}")
    if bad:
        raise SystemExit("与 v3_summary_method_scale.csv 不一致：\n  " + "\n  ".join(bad))
    print("自检：逐单元重算的三项中位数与 v3_summary_method_scale.csv 完全一致")


