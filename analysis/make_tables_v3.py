def write_outputs(tabs: list[Tab], check_only: bool = False) -> None:
    TDIR.mkdir(parents=True, exist_ok=True)
    repo_docs = ROOT / "code_for_paper_github" / "docs"
    repo_docs.mkdir(parents=True, exist_ok=True)
    md_parts = [MD_PREAMBLE]
    for t in tabs:
        tex = render_tex(t)
        md_parts.append(render_md(t))
        if check_only:
            continue
        outdir = repo_docs if t.fname == "tab_drill_per_run.tex" else TDIR
        path = outdir / t.fname
        path.write_text(tex, encoding="utf-8", newline="\n")
        print(f"写入 {path.relative_to(ROOT)}（{len(tex.splitlines())} 行）")
    if check_only:
        return
    md_parts.append(
        "## 删除说明\n\n"
        "S4（评估口径探针表）与 S6（共同参考阈值密度表）已拍板删除，本版不生成；"
        "SI 表号在接线时按剩余表的 \\input 顺序自动重排。\n"
    )
    MD_OUT.write_text("\n".join(md_parts), encoding="utf-8", newline="\n")
    print(f"写入 {MD_OUT.relative_to(ROOT)}")


def main() -> None:
    ap = argparse.ArgumentParser(description="v3 论文表格生成")
    ap.add_argument("--check", action="store_true", help="只算不写（自检）")
    args = ap.parse_args()
    if not ANA.exists():
        raise SystemExit(f"分析目录不存在：{ANA}")
    d = Data()
    check_against_summary(d)
    tabs = build(d)
    write_outputs(tabs, check_only=args.check)
    print(f"共 {len(tabs)} 张表：" + "、".join(t.fname for t in tabs))


if __name__ == "__main__":
    main()
